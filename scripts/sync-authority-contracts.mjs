/** P0-04A: generate immutable Shared authority schemas, not local policy.
 * Read Git blobs rather than mutable checkout files, require the exact pin,
 * and walk every external $ref. Runtime never fetches schemas over the network.
 */
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, posix, resolve } from "node:path"
import { parse } from "yaml"
import { format, resolveConfig } from "prettier"

const root = resolve(import.meta.dirname, "..")
const shared = process.env.BAOBAB_SHARED_PATH
if (!shared) throw new Error("BAOBAB_SHARED_PATH must name the exact pinned Shared checkout")
const lock = parse(readFileSync(join(root, "contracts.lock.yaml"), "utf8"))
const git = (...args) => execFileSync("git", ["-C", shared, ...args], { encoding: "utf8" })
if (git("rev-parse", "HEAD").trim() !== lock.source.commit) throw new Error("Shared pin mismatch")
const target = join(root, "src/baobab/contracts/shared")
const roots = [
  "contracts/commerce/v1/seller-binding.schema.json",
  "contracts/payments/v1/merchant-readiness.schema.json",
  "contracts/organisation/v2/legal-actor-enforcement.schema.json",
  "contracts/admission/v2/documentary-restriction.schema.json",
  "contracts/control-plane/v1/platform-context.schema.json",
  "contracts/trade/v2/seller-operating-binding.schema.json",
  "contracts/trade/v2/order-authority.schema.json",
  "contracts/identity/v1/buyer-identity-handoff.schema.json",
  "contracts/identity/v1/assurance-policy.schema.json",
  "contracts/control-plane/v1/estate-client-binding.schema.json",
  "contracts/trade/v2/buyer-execution-context.schema.json",
  "contracts/trade/v2/buyer-spend-budget.schema.json",
  // ADR-SHARED-042 section 14 Decisions 6-8.
  "contracts/trade/v2/buyer-authority-receipt.schema.json",
  "contracts/trade/v2/buyer-commitment-valuation.schema.json",
  "contracts/control-plane/v1/estate-commerce-profile.schema.json",
  "contracts/trade/v2/native-commitment-classification.schema.json",
  // Decision 9.
  "contracts/control-plane/v1/estate-resource-assignment.schema.json",
]
const schemas = new Map()
const discover = (path) => {
  if (schemas.has(path)) return
  if (!path.startsWith("contracts/") || !path.endsWith(".schema.json"))
    throw new Error(`Unexpected Shared schema reference: ${path}`)
  const raw = git("show", `${lock.source.commit}:${path}`)
  const schema = JSON.parse(raw)
  schemas.set(path, { raw, schema })
  const walk = (value) => {
    if (!value || typeof value !== "object") return
    if (typeof value.$ref === "string") {
      const file = value.$ref.split("#")[0]
      if (file) {
        if (file.includes(":")) throw new Error("Remote schema reference is not permitted")
        discover(posix.normalize(posix.join(posix.dirname(path), file)))
      }
    }
    for (const child of Object.values(value)) walk(child)
  }
  walk(schema)
}
roots.forEach(discover)
const files = [...schemas.keys()].sort()
for (const path of files) {
  if (!lock.contracts.includes(path)) throw new Error(`Declare consumed closure in lock: ${path}`)
}
// Replace only the generated closure after all reads/declarations succeeded.
// Removed upstream references must not leave stale, undeclared schemas behind.
rmSync(join(target, "contracts"), { recursive: true, force: true })
for (const path of files) {
  const output = join(target, path)
  mkdirSync(dirname(output), { recursive: true })
  writeFileSync(output, schemas.get(path).raw)
}
const manifest = {
  repository: lock.source.repository,
  commit: lock.source.commit,
  roots,
  tenancy_version: parse(git("show", `${lock.source.commit}:contracts/tenancy/tenancy.yaml`)).schema
    .version,
  files: Object.fromEntries(
    files.map((path) => [path, createHash("sha256").update(schemas.get(path).raw).digest("hex")]),
  ),
}
writeFileSync(join(target, "provenance.json"), JSON.stringify(manifest, null, 2) + "\n")
const authority = schemas.get("contracts/organisation/v2/legal-actor-mandate.schema.json").schema
const outcomes = authority.$defs.LegalActorResolution.properties.outcome.enum
const imports = files.map((path, i) => `import schema${i} from "./shared/${path}"`).join("\n")
const generatedPath = join(root, "src/baobab/contracts/authority-schemas.generated.ts")
const generated =
  `// Generated by npm run contracts:sync from Shared ${lock.source.commit}.\n` +
  `// Do not edit: schema ownership remains in Shared; no runtime network resolution.\n` +
  `${imports}\n\nexport const authoritySchemas = [${files.map((_, i) => `schema${i}`).join(", ")}]\n` +
  `export const LEGAL_ACTOR_OUTCOMES = ${JSON.stringify(outcomes)} as const\n`
writeFileSync(
  generatedPath,
  await format(generated, { ...(await resolveConfig(generatedPath)), filepath: generatedPath }),
)
