import { describe, expect, it } from "vitest"
import parity from "./fixtures/buyer-commitment-valuation-parity.json"
import { buyerCommitmentValuationSchema } from "../src/baobab/contracts/authority-validation"
import {
  buildFinalBuyerCommitmentValuation,
  valuationDigest,
  type FinalNativeValuationFacts,
} from "../src/baobab/b2b/buyer-commitment-valuation"

/** Exact accepted Shared #430 reference example:
 * contracts/trade/v2/examples/buyer-commitment-valuation-order-commit.json
 *
 * These unit fixtures are not real Medusa prices, a buyer IAM/CP decision,
 * a spend reservation or a native source attestation.
 */
const REFERENCE: FinalNativeValuationFacts = {
  resource_id: "cart_synthetic01",
  resource_version: 4,
  transaction_digest: "sha256:9f2c4e6a8b0d1f3e9f2c4e6a8b0d1f3e9f2c4e6a8b0d1f3e9f2c4e6a8b0d1f3e",
  currency: "UGX",
  basis: "FINAL_PRICED",
  components: [
    {
      component_kind: "MERCHANDISE",
      amount_minor: 1_100_000,
      determination: "FINAL",
      source_reference: "line_synthetic01",
    },
    {
      component_kind: "ORDER_DISCOUNT",
      amount_minor: -50_000,
      determination: "FINAL",
      source_reference: "adjustment_synthetic01",
    },
    {
      component_kind: "SHIPPING",
      amount_minor: 50_000,
      determination: "FINAL",
      source_reference: "shipping_method_synthetic01",
    },
    {
      component_kind: "TAX",
      amount_minor: 150_000,
      determination: "FINAL",
      source_reference: "tax_line_synthetic01",
    },
  ],
}
const TIME = new Date("2026-10-21T11:59:58Z")
const val = (candidate: unknown) => buildFinalBuyerCommitmentValuation(candidate, TIME)

describe("CAA-06b final buyer obligation (non-binding source kernel)", () => {
  it.each(parity.vectors)("matches the actual accepted Shared reference: $name", (vector) => {
    // These expected hashes were generated by Shared's Python implementation
    // and validated there, independently of this TypeScript implementation.
    const original = JSON.stringify(vector.facts)
    for (const components of [vector.facts.components, [...vector.facts.components].reverse()]) {
      const valuation = val({ ...vector.facts, components })
      expect(valuation.buyer_commitment_amount_minor).toBe(vector.expected_amount_minor)
      expect(valuation.valuation_digest).toBe(vector.expected_digest)
      expect(buyerCommitmentValuationSchema(valuation)).toBe(true)
    }
    expect(JSON.stringify(vector.facts)).toBe(original)
  })

  it("refuses a genuinely unsafe final amount after summing every component", () => {
    const components = [
      {
        component_kind: "MERCHANDISE",
        amount_minor: Number.MAX_SAFE_INTEGER,
        determination: "FINAL",
        source_reference: "line",
      },
      { component_kind: "TAX", amount_minor: 1, determination: "FINAL", source_reference: "tax" },
    ]
    for (const ordered of [components, [...components].reverse()]) {
      expect(() => val({ ...REFERENCE, components: ordered })).toThrow("VALUATION_UNSAFE_AMOUNT")
    }
  })

  it("rejects invalid Unicode and clocks that cannot produce the canonical date-time", () => {
    for (const resource_id of ["\ud800", "cart_\udfff", "🌍".repeat(129)]) {
      expect(() => val({ ...REFERENCE, resource_id })).toThrow("VALUATION_INVALID")
    }
    for (const time of [
      new Date(NaN),
      new Date("0000-01-01T00:00:00Z"),
      new Date("+010000-01-01T00:00:00Z"),
    ]) {
      expect(() => buildFinalBuyerCommitmentValuation(REFERENCE, time)).toThrow("VALUATION_INVALID")
    }
  })

  it("agrees with accepted Shared #430 canonical SHA-256, irrespective of input order", () => {
    const reference = val(REFERENCE)
    expect(reference.buyer_commitment_amount_minor).toBe(1_250_000)
    expect(reference.currency).toBe("UGX")
    expect(reference.valuation_digest).toBe(
      "sha256:ec293faad4e8175b85ec59a2fffe99035860b132d9f2b8d811619ec27c4cc429",
    )
    expect(reference.valuation_id).toMatch(/^[0-9a-f-]{36}$/)
    expect(reference.valued_at).toBe("2026-10-21T11:59:58.000Z")
    expect(
      val({ ...REFERENCE, components: [...REFERENCE.components].reverse() }).valuation_digest,
    ).toBe(reference.valuation_digest)
    expect(valuationDigest(reference)).toBe(reference.valuation_digest)
  })

  it("commits the entire obligation, including tax, freight and handling, not tender", () => {
    const due = val({
      ...REFERENCE,
      currency: "ZAR",
      components: [
        {
          component_kind: "MERCHANDISE",
          amount_minor: 4_000_000,
          determination: "FINAL",
          source_reference: "line_coffee",
        },
        {
          component_kind: "ORDER_DISCOUNT",
          amount_minor: -200_000,
          determination: "FINAL",
          source_reference: "adjustment_volume",
        },
        {
          component_kind: "SHIPPING",
          amount_minor: 150_000,
          determination: "FINAL",
          source_reference: "freight_road",
        },
        {
          component_kind: "HANDLING",
          amount_minor: 50_000,
          determination: "FINAL",
          source_reference: "handling_port",
        },
        {
          component_kind: "TAX",
          amount_minor: 600_000,
          determination: "FINAL",
          source_reference: "tax_vat",
        },
      ],
    })
    // Merchandise R40,000 - discount R2,000 + freight/handling R2,000
    // + VAT R6,000 = R46,000. Paying a deposit never reduces it.
    expect(due.buyer_commitment_amount_minor).toBe(4_600_000)
  })

  it("refuses tender, discounts as charges, negative taxes and estimates", () => {
    for (const kind of [
      "STORE_CREDIT",
      "WALLET",
      "GIFT_CARD",
      "PAYMENT_ON_ACCOUNT",
      "DEPOSIT_COLLECTED",
      "CREDIT_TERMS",
    ]) {
      expect(() =>
        val({
          ...REFERENCE,
          components: [
            ...REFERENCE.components,
            {
              component_kind: kind,
              amount_minor: -1,
              determination: "FINAL",
              source_reference: "tender",
            },
          ],
        }),
      ).toThrow("VALUATION_INVALID")
    }
    for (const addition of [
      {
        component_kind: "ITEM_DISCOUNT",
        amount_minor: 1,
        determination: "FINAL",
        source_reference: "bad_discount",
      },
      {
        component_kind: "TAX",
        amount_minor: -1,
        determination: "FINAL",
        source_reference: "bad_tax",
      },
    ]) {
      expect(() => val({ ...REFERENCE, components: [...REFERENCE.components, addition] })).toThrow(
        "VALUATION_INVALID_CHARGE_SIGN",
      )
    }
    expect(() =>
      val({
        ...REFERENCE,
        components: [
          ...REFERENCE.components,
          {
            component_kind: "DUTY_AND_IMPORT_CHARGE",
            amount_minor: 50,
            determination: "ESTIMATED",
            source_reference: "estimate",
          },
        ],
      }),
    ).toThrow("VALUATION_NOT_FINAL")
  })

  it("does not activate unqualified GOVERNED_MAXIMUM or trust client injection", () => {
    expect(() =>
      val({ ...REFERENCE, basis: "GOVERNED_MAXIMUM", maximum_commitment_reference: "maximum_123" }),
    ).toThrow("VALUATION_INVALID")
    expect(() => val({ ...REFERENCE, actor_principal_id: "role_admin" })).toThrow(
      "VALUATION_INVALID",
    )
    expect(() => val({ ...REFERENCE, buyer_commitment_amount_minor: 1 })).toThrow(
      "VALUATION_INVALID",
    )
    expect(() => val({ ...REFERENCE, valuation_digest: "sha256:" + "0".repeat(64) })).toThrow(
      "VALUATION_INVALID",
    )
  })

  it("requires one native merchandise fact and unique source identifiers", () => {
    expect(() =>
      val({
        ...REFERENCE,
        components: REFERENCE.components.filter((c) => c.component_kind !== "MERCHANDISE"),
      }),
    ).toThrow("VALUATION_MERCHANDISE_REQUIRED")
    expect(() =>
      val({
        ...REFERENCE,
        components: [...REFERENCE.components, REFERENCE.components[0]],
      }),
    ).toThrow("VALUATION_DUPLICATE_NATIVE_FACT")
    expect(() =>
      val({
        ...REFERENCE,
        components: [
          ...REFERENCE.components,
          { ...REFERENCE.components[0], source_reference: "a person\nnot a native ID" },
        ],
      }),
    ).toThrow("VALUATION_INVALID")
  })

  it("refuses unsafe integers, negative or absent total and stale resource version", () => {
    expect(() =>
      val({
        ...REFERENCE,
        components: [
          {
            component_kind: "MERCHANDISE",
            amount_minor: Number.MAX_SAFE_INTEGER + 1,
            determination: "FINAL",
            source_reference: "unsafe",
          },
        ],
      }),
    ).toThrow("VALUATION_UNSAFE_AMOUNT")
    expect(() =>
      val({
        ...REFERENCE,
        components: [
          {
            component_kind: "MERCHANDISE",
            amount_minor: 0,
            determination: "FINAL",
            source_reference: "free",
          },
        ],
      }),
    ).toThrow("VALUATION_UNSAFE_AMOUNT")
    expect(() => val({ ...REFERENCE, resource_version: 0 })).toThrow("VALUATION_INVALID")
    expect(() => val({ ...REFERENCE, currency: "Zar" })).toThrow("VALUATION_INVALID")
    expect(() => val({ ...REFERENCE, transaction_digest: "untrusted" })).toThrow(
      "VALUATION_INVALID",
    )
  })

  it("material source changes always force a different binding digest", () => {
    const reference = val(REFERENCE)
    for (const changed of [
      { ...REFERENCE, resource_version: 5 },
      { ...REFERENCE, currency: "ZAR" },
      { ...REFERENCE, transaction_digest: "sha256:" + "b".repeat(64) },
      {
        ...REFERENCE,
        components: REFERENCE.components.map((c, i) =>
          i === 0 ? { ...c, amount_minor: c.amount_minor + 1 } : c,
        ),
      },
    ]) {
      expect(val(changed).valuation_digest).not.toBe(reference.valuation_digest)
    }
  })
})
